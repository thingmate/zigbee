describe('decodeZCLDataTypeUnknown', (): void => {
  test('decodes every supported data type.', (): void => {
    for (const [dataType, bytes, expected] of samples) {
      expect(
        Decoder.decode(bytes, (decoder: Decoder): unknown =>
          decodeZCLDataTypeUnknown(decoder, dataType),
        ),
      ).toEqual(expected);
    }
  });

  test('throws on an unsupported data type.', (): void => {
    expect((): unknown =>
      Decoder.decode(new Uint8Array([0x7f]), (decoder: Decoder): unknown =>
        decodeZCLDataTypeUnknown(decoder, 0x7f),
      ),
    ).toThrow('Unsupported data type: 0x7f.');
  });
});

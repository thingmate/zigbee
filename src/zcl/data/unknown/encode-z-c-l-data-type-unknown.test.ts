describe('encodeZCLDataTypeUnknown', (): void => {
  test('encodes every supported data type.', (): void => {
    for (const [dataType, value, bytes] of samples) {
      const encoder: Encoder = new Encoder();
      encodeZCLDataTypeUnknown(encoder, dataType, value);
      expect(encoder.toUint8Array()).toEqual(bytes);
    }
  });

  test('throws on an unsupported data type.', (): void => {
    const encoder: Encoder = new Encoder();
    expect((): void => {
      encodeZCLDataTypeUnknown(encoder, 0x7f, 0);
    }).toThrow('Unsupported data type: 0x7f.');
  });
});
